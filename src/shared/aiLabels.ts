import { AIAnalysis, AIFallbackReason } from './types.js';

export const FALLBACK_REASON_TEXT: Record<AIFallbackReason, string> = {
  not_configured: 'AI is not configured on this server',
  rate_limited: 'the AI service quota or rate limit was reached',
  timeout: 'the AI service did not respond in time',
  model_unavailable: 'the configured AI model is not available',
  invalid_key: 'the AI service rejected the server credentials',
  invalid_response: 'the AI service returned an unusable response',
  service_error: 'the AI service returned an error'
};

/** Short title naming what actually produced the suggestions. */
export function aiSourceTitle(analysis: Pick<AIAnalysis, 'isAiFallback'>): string {
  return analysis.isAiFallback ? 'Keyword-Rule Suggestions (AI unavailable)' : 'Gemini AI Suggestions';
}

/** One-line explanation, including the model or the reason Gemini was not used. */
export function aiSourceDetail(analysis: Pick<AIAnalysis, 'isAiFallback' | 'fallbackReason' | 'model'>): string {
  if (analysis.isAiFallback) {
    // Older records have no reason recorded
    const reason = analysis.fallbackReason ? FALLBACK_REASON_TEXT[analysis.fallbackReason] : 'AI was not used';
    return `Generated by simple keyword rules because ${reason}. Please check and edit.`;
  }
  return `Generated by ${analysis.model || 'Gemini'}. Suggestions only — please check and edit.`;
}
